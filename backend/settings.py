def _first_database_url_raw() -> str:
    """Cadena de conexión; varias plataformas usan nombres distintos."""
    for key in (
        "DATABASE_URL",
        "POSTGRES_URL",
        "POSTGRESQL_URL",
        "POSTGRES_DATABASE_URL",
    ):
        v = (os.environ.get(key) or "").strip()
        if v and not v.startswith("${"):
            # Valor enlazado no resuelto en el panel de DO (literal ${db...})
            return v
    return ""


def _database_from_url() -> dict | None:
    """DigitalOcean App Platform suele inyectar DATABASE_URL al vincular PostgreSQL."""
    raw = _first_database_url_raw()
    if not raw:
        return None
    u = urlparse(raw)
    if u.scheme not in ("postgres", "postgresql"):
        return None
    path = (u.path or "").lstrip("/")
    dbname = path.split("/")[0] or "postgres"
    opts: dict = {"connect_timeout": 10}
    q = parse_qs(u.query)
    if q.get("sslmode"):
        opts["sslmode"] = q["sslmode"][0]
    elif u.hostname and "digitalocean" in u.hostname:
        opts["sslmode"] = "require"
    if _postgres_sslmode and "sslmode" not in opts:
        opts["sslmode"] = _postgres_sslmode
    user = (unquote_plus(u.username or "") or "").strip()
    password = (unquote_plus(u.password or "") or "").strip()
    # Si la contraseña en la URL está mal copiada o con caracteres que rompen el parseo,
    # defina POSTGRES_PASSWORD (o PGPASSWORD) en el panel: sustituye la de DATABASE_URL.
    _pw_override = (os.environ.get("POSTGRES_PASSWORD") or os.environ.get("PGPASSWORD") or "").strip()
    if _pw_override:
        password = _pw_override
    return {
        "ENGINE": "django.db.backends.postgresql",
        "NAME": unquote_plus(dbname),
        "USER": user,
        "PASSWORD": password,
        "HOST": u.hostname or "",
        "PORT": str(u.port or 5432),
        "OPTIONS": opts,
    }


def _database_from_pg_env() -> dict | None:
    """Variables estilo libpq (PGHOST, PGDATABASE, …) que algunos entornos inyectan."""
    host = (
        (os.environ.get("PGHOST") or os.environ.get("POSTGRES_HOSTNAME") or "").strip()
    )
    if not host:
        return None
    opts: dict = {"connect_timeout": 10}
    if _postgres_sslmode:
        opts["sslmode"] = _postgres_sslmode
    elif "digitalocean" in host:
        opts["sslmode"] = "require"
    return {
        "ENGINE": "django.db.backends.postgresql",
        "NAME": (os.environ.get("PGDATABASE") or env.str("POSTGRES_DB", default="paredes_bienes")).strip(),
        "USER": (os.environ.get("PGUSER") or "").strip(),
        "PASSWORD": (os.environ.get("PGPASSWORD") or "").strip(),
        "HOST": host,
        "PORT": str((os.environ.get("PGPORT") or "5432")).strip(),
        "OPTIONS": opts,
    }


