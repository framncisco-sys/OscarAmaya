def _solo_direccion_correo(valor: str) -> str:
    """Extrae correo@dominio de 'Nombre <correo@dominio>' o devuelve el string recortado."""
    s = (valor or "").strip()
    if not s:
        return ""
    m = re.search(r"<([^>]+)>", s)
    if m:
        return m.group(1).strip()
    return s


def _resolver_default_from_email() -> str:
    """Remitente de recibos: explícito en .env o alineado con la cuenta SMTP (evita rechazos del hosting)."""
    raw = env.str("DEFAULT_FROM_EMAIL", default="").strip()
    placeholder = "noreply@paredes.local"
    if raw and raw != placeholder:
        return raw
    if EMAIL_HOST_USER:
        nombre = env.str("DEFAULT_FROM_EMAIL_NAME", default="Paredes Desarrollos Inmobiliarios").strip()
        return f"{nombre} <{EMAIL_HOST_USER}>"
    return raw or placeholder


